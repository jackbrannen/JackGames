#!/usr/bin/env node
// Parses emoji-list.md (the editable source of truth) into lib/emojis.js.
// Rerun after editing the md file.
//
// Usage: node scripts/build-emoji-list.mjs

import { readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const MD_PATH = path.join(__dirname, "..", "emoji-list.md")
const OUT_PATH = path.join(__dirname, "..", "lib", "emojis.js")

const segmenter = new Intl.Segmenter("en", { granularity: "grapheme" })

function extractEmoji(line) {
  return [...segmenter.segment(line)]
    .map((s) => s.segment)
    .filter((g) => /\p{Extended_Pictographic}/u.test(g) || /\p{Regional_Indicator}/u.test(g))
}

function main() {
  const md = readFileSync(MD_PATH, "utf8")
  const lines = md.split("\n")

  let category = null
  const entries = []
  const seen = new Set()

  for (const line of lines) {
    const heading = line.match(/^##\s+(.+?)(\s*\(.*\))?$/)
    if (heading) {
      category = heading[1].trim()
      continue
    }
    if (!category || line.startsWith("#")) continue

    for (const emoji of extractEmoji(line)) {
      if (seen.has(emoji)) continue
      seen.add(emoji)
      entries.push({ emoji, category })
    }
  }

  const banner = "// Generated by scripts/build-emoji-list.mjs from emoji-list.md — do not hand-edit, edit the md and rerun.\n"
  const body = `export const EMOJIS = ${JSON.stringify(entries, null, 2)}\n`
  writeFileSync(OUT_PATH, banner + body)

  console.log(`Wrote ${entries.length} emoji to lib/emojis.js`)
}

main()
